//! Bakes the engine's git commit into `EVANI_GIT_COMMIT` (short hash, or
//! `unknown` without git or outside a repository), so the overlay and live
//! `session.status` can say exactly which Evani.Dev a game was built from.
//!
//! Git itself answers where HEAD and its branch ref live, so a linked
//! worktree (whose `.git` is a file pointing at the real git dir) and
//! packed refs are handled the same as a plain checkout; the build reruns
//! when any of them moves.

//!
//! It also compiles the built-in quality tiers (`assets/tiers/*.json`, the
//! source of truth that people, agents and `bake.export` edit) into a Rust
//! table, `$OUT_DIR/builtin_tiers.rs`, so a game carries the numbers as data
//! and no JSON text or tier parser (README "How data ships").

use std::path::{Path, PathBuf};
use std::process::Command;

mod tiers {
    //! `assets/tiers/<id>.json` -> `static BUILTIN_TIERS: [TierRow; N]`.
    //! The rules are `TierPreset`'s serde ones (required fields, `msaa`
    //! default 1 and only 1 or 4, optional shadow fields); a test in
    //! tiers.rs checks the table equals what `TierPreset::from_json` reads.
    use serde_json::{Map, Value};
    use std::fmt::Write as _;
    use std::path::Path;

    /// Ascending order, the same as `BUILTIN_TIER_JSON`.
    const IDS: [&str; 6] = ["lite", "low", "medium", "high", "ultra", "vr"];

    pub fn write(dir: &Path) -> Result<(), String> {
        let assets = dir.join("../../assets/tiers");
        let mut out = String::from(
            "// Generated by evani-core's build.rs from assets/tiers/*.json; edit the JSON.\n\
             pub(crate) static BUILTIN_TIERS: [TierRow; 6] = [\n",
        );
        for id in IDS {
            let path = assets.join(format!("{id}.json"));
            println!("cargo:rerun-if-changed={}", path.display());
            let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
            let v: Value = serde_json::from_str(&text).map_err(|e| format!("{id}.json: {e}"))?;
            let o = v.as_object().ok_or_else(|| format!("{id}.json: not an object"))?;
            row(&mut out, o).map_err(|e| format!("{id}.json: {e}"))?;
        }
        out.push_str("];\n");
        let dest = std::env::var("OUT_DIR").map_err(|e| e.to_string())?;
        std::fs::write(Path::new(&dest).join("builtin_tiers.rs"), out).map_err(|e| e.to_string())
    }

    fn row(out: &mut String, o: &Map<String, Value>) -> Result<(), String> {
        let msaa = match o.get("msaa") {
            None => 1,
            Some(v) => u32_of(v, "msaa")?,
        };
        if !matches!(msaa, 1 | 4) {
            return Err(format!("msaa must be 1 or 4, not {msaa}"));
        }
        out.push_str("    TierRow {\n");
        for f in ["id", "label"] {
            let s = req(o, f)?.as_str().ok_or_else(|| format!("{f}: not a string"))?;
            let _ = writeln!(out, "        {f}: {s:?},");
        }
        for f in ["fps_target", "max_draw_calls", "max_triangles", "max_sprites", "max_particles", "points"] {
            let _ = writeln!(out, "        {f}: {},", u32_of(req(o, f)?, f)?);
        }
        // Megabytes, read only with the `texture-budget` feature (a game that
        // lists `models`); without it the field does not exist in the table.
        let _ = writeln!(
            out,
            "        #[cfg(feature = \"texture-budget\")]\n        max_texture_memory: {},",
            u32_of(req(o, "max_texture_memory")?, "max_texture_memory")?
        );
        // Point lights per frame, read only with `point-lights` (evani-render's
        // feature); optional in the JSON, 0 = none.
        let lights = match o.get("max_point_lights") {
            None => 0,
            Some(v) => u32_of(v, "max_point_lights")?,
        };
        let _ = writeln!(out, "        #[cfg(feature = \"point-lights\")]\n        max_point_lights: {lights},");
        // Sun shadow cascades, read only with `shadow-cascades` (evani-render's
        // feature); optional in the JSON, default 1 (one shadow map, as before).
        let cascades = match o.get("shadow_cascades") {
            None => 1,
            Some(v) => u32_of(v, "shadow_cascades")?,
        };
        let _ = writeln!(out, "        #[cfg(feature = \"shadow-cascades\")]\n        shadow_cascades: {cascades},");
        // Sky-cube face size for image-based lighting, read only with `ibl`
        // (evani-render's feature); optional, 0 = the analytic sky (no cube).
        let cube = match o.get("ibl_cube") {
            None => 0,
            Some(v) => u32_of(v, "ibl_cube")?,
        };
        let _ = writeln!(out, "        #[cfg(feature = \"ibl\")]\n        ibl_cube: {cube},");
        // Ground-truth AO quality, read only with `gtao` (evani-render's
        // feature); optional, 0 = off, 1 = half-res Low, 2 = Medium, 3 = High.
        let gtao = match o.get("gtao") {
            None => 0,
            Some(v) => u32_of(v, "gtao")?,
        };
        let _ = writeln!(out, "        #[cfg(feature = \"gtao\")]\n        gtao: {gtao},");
        let _ = writeln!(out, "        msaa: {msaa},");
        for f in ["fps_max", "fps_floor", "shadow_map", "shadow_pcf"] {
            let v = match o.get(f) {
                None | Some(Value::Null) => "None".to_string(),
                Some(v) => format!("Some({})", u32_of(v, f)?),
            };
            let _ = writeln!(out, "        {f}: {v},");
        }
        for f in ["refresh_hz", "target_resolution"] {
            let v = match req(o, f)? {
                Value::Null => "None".to_string(),
                Value::Array(a) if a.len() == 2 => format!("Some([{}, {}])", u32_of(&a[0], f)?, u32_of(&a[1], f)?),
                _ => return Err(format!("{f}: not null or two numbers")),
            };
            let _ = writeln!(out, "        {f}: {v},");
        }
        for f in ["render_scale", "dpr_cap"] {
            let v = match req(o, f)? {
                Value::Null => "None".to_string(),
                // The f32 serde_json reads (f64, then `as f32`), as exact bits.
                v => {
                    let x = v.as_f64().ok_or_else(|| format!("{f}: not a number"))? as f32;
                    format!("Some(f32::from_bits({:#010x})) /* {x} */", x.to_bits())
                }
            };
            let _ = writeln!(out, "        {f}: {v},");
        }
        for f in ["stereo", "auto_select"] {
            let b = req(o, f)?.as_bool().ok_or_else(|| format!("{f}: not true or false"))?;
            let _ = writeln!(out, "        {f}: {b},");
        }
        let fx = req(o, "effects_on")?
            .as_array()
            .ok_or("effects_on: not a list")?
            .iter()
            .map(|e| e.as_str().map(|s| format!("{s:?}")).ok_or("effects_on: not a list of names"))
            .collect::<Result<Vec<_>, _>>()?;
        let _ = writeln!(out, "        effects_on: &[{}],", fx.join(", "));
        out.push_str("    },\n");
        Ok(())
    }

    fn req<'a>(o: &'a Map<String, Value>, f: &str) -> Result<&'a Value, String> {
        o.get(f).ok_or_else(|| format!("missing field `{f}`"))
    }

    fn u32_of(v: &Value, f: &str) -> Result<u32, String> {
        v.as_u64()
            .and_then(|n| u32::try_from(n).ok())
            .ok_or_else(|| format!("{f}: not a whole number from 0 to {}", u32::MAX))
    }
}

fn git(dir: &Path, args: &[&str]) -> Option<String> {
    let out = Command::new("git").current_dir(dir).args(args).output().ok()?;
    if !out.status.success() {
        return None;
    }
    let s = String::from_utf8(out.stdout).ok()?.trim().to_string();
    (!s.is_empty()).then_some(s)
}

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into()));
    // `--cfg evani_headless`: a referee build (no browser glue, no imports).
    println!("cargo::rustc-check-cfg=cfg(evani_headless)");
    // The built-in tier table, compiled from assets/tiers/*.json (first, so
    // its files are tracked in every build, the live code-swap one too).
    if let Err(e) = tiers::write(&dir) {
        panic!("evani-core: assets/tiers: {e}");
    }
    // Overridable (reproducible builds, or a build from a source tarball).
    println!("cargo:rerun-if-env-changed=EVANI_GIT_COMMIT");
    let given = std::env::var("EVANI_GIT_COMMIT").ok().filter(|s| !s.trim().is_empty());
    let overridden = given.is_some();
    let commit = given
        .or_else(|| git(&dir, &["rev-parse", "--short=7", "HEAD"]))
        .unwrap_or_else(|| "unknown".to_string());
    println!("cargo:rustc-env=EVANI_GIT_COMMIT={commit}");
    if overridden {
        // Given from outside (live code swapping sets it for its dx build):
        // no git files are tracked, so a commit or restore never sets off a
        // code swap (docs/LIVE_API.md 10.4).
        return;
    }

    // Rerun when HEAD moves: the worktree's own HEAD, the branch ref it
    // points at, and packed-refs (where a ref goes after `git gc`).
    let abs = |p: String| {
        let p = PathBuf::from(p);
        if p.is_absolute() { p } else { dir.join(p) }
    };
    if let Some(git_dir) = git(&dir, &["rev-parse", "--git-dir"]).map(abs) {
        println!("cargo:rerun-if-changed={}", git_dir.join("HEAD").display());
        let common = git(&dir, &["rev-parse", "--git-common-dir"]).map_or(git_dir.clone(), abs);
        if let Some(r) = git(&dir, &["symbolic-ref", "-q", "HEAD"]) {
            for base in [&git_dir, &common] {
                let p = base.join(&r);
                if p.is_file() {
                    println!("cargo:rerun-if-changed={}", p.display());
                }
            }
        }
        let packed = common.join("packed-refs");
        if packed.is_file() {
            println!("cargo:rerun-if-changed={}", packed.display());
        }
    }
}
