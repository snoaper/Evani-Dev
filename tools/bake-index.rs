//! Shared build script for looks and kits (`build = "../../tools/bake-index.rs"`).
//!
//! Embeds the crate's baked files (written by `bake.export`, docs/LIVE_API.md
//! 6.23) so a shipped build reproduces the tuned values with no live code and
//! no runtime file access. Writes `$OUT_DIR/baked.rs`:
//!
//! ```ignore
//! pub const BAKED: &[(&str, &str)] = &[("params.json", include_str!("…")), …];
//! ```
//!
//! The crate does `include!(concat!(env!("OUT_DIR"), "/baked.rs"));` and calls
//! `ctx.baked_files(BAKED)` in its `build`. Files picked up (paths relative to
//! the crate root, sorted): `params.json`, `policy.json`, `slots/*.wgsl`,
//! `slots/*.expr`, `curves/*.json`.
//!
//! Live code swapping (docs/LIVE_API.md 10.4) sets `EVANI_BAKED_STAMP` (a
//! hash of every look's and kit's baked files) for its dx build. Then the
//! contents are written into `baked.rs` as literals and no data file or
//! folder is listed for change tracking, so a bake (or a restore of baked
//! files) never sets off a Rust code swap; the live server hands the page
//! the newer files instead. A new stamp (a new dx start) reruns this script.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs, io};

fn main() -> io::Result<()> {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").map_err(io::Error::other)?);
    let out = PathBuf::from(env::var("OUT_DIR").map_err(io::Error::other)?);
    println!("cargo:rerun-if-env-changed=EVANI_BAKED_STAMP");
    let stamped = env::var("EVANI_BAKED_STAMP").is_ok_and(|s| !s.trim().is_empty());
    if !stamped {
        // A directory makes Cargo rescan the whole crate for changes, so new
        // baked files are picked up without touching the source.
        println!("cargo:rerun-if-changed=.");
    }

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    for name in ["params.json", "policy.json"] {
        let p = root.join(name);
        if p.is_file() {
            files.push((name.to_string(), p));
        }
    }
    collect(&root, "slots", &["wgsl", "expr"], &mut files)?;
    collect(&root, "curves", &["json"], &mut files)?;
    files.sort();

    let mut src = String::from("/// Baked files of this crate (generated by tools/bake-index.rs).\n");
    src.push_str("pub const BAKED: &[(&str, &str)] = &[\n");
    for (rel, abs) in &files {
        if stamped {
            // Debug formatting escapes the text: a valid string literal.
            let text = fs::read_to_string(abs)?;
            let _ = writeln!(src, "    ({rel:?}, {text:?}),");
        } else {
            let abs = abs.to_string_lossy();
            // Debug formatting escapes backslashes and quotes: a valid literal.
            let _ = writeln!(src, "    ({rel:?}, include_str!({abs:?})),");
        }
    }
    src.push_str("];\n");
    fs::write(out.join("baked.rs"), src)
}

fn collect(
    root: &Path,
    dir: &str,
    exts: &[&str],
    files: &mut Vec<(String, PathBuf)>,
) -> io::Result<()> {
    let d = root.join(dir);
    if !d.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(&d)? {
        let p = entry?.path();
        if !p.is_file() {
            continue;
        }
        let ext = p.extension().and_then(|e| e.to_str()).unwrap_or("");
        let Some(name) = p.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if exts.contains(&ext) {
            files.push((format!("{dir}/{name}"), p.clone()));
        }
    }
    Ok(())
}
