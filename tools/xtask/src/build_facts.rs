//! `build-facts.json`: the short, portal-neutral statement `cargo xtask build
//! <id> --ship` (and `publish`) writes next to a shipped game's index.html.
//!
//! It is generated, never hand-kept: the module list, look and kit come from
//! `evani.toml`, the sizes from the ship build, the engine commit from git
//! (the same short hash evani-core's build.rs bakes into the wasm), and the
//! engine's own fixed facts (no ads, no analytics, no cookies, no requests to
//! other sites) are stated here once, with the module that would change each
//! one (`net`). Nothing page.html loads refers to it, so it is no part of the
//! download: 0 bytes in the wasm, js or html. Only `[statement]` in
//! evani.toml (the game's licence and any third-party files) is author-written.

use crate::{AppDir, BuildSize, Manifest};
use serde_json::{Value, json};
use std::path::Path;

pub const FACTS_FILE: &str = "build-facts.json";

/// The author-written part, from the optional `[statement]` table.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Statement {
    pub game_licence: Option<String>,
    pub third_party: Vec<String>,
}

impl Statement {
    pub fn parse(toml_text: &str) -> Result<Self, String> {
        let t: toml::Table = toml_text.parse().map_err(|e| format!("evani.toml: {e}"))?;
        let Some(s) = t.get("statement") else { return Ok(Self::default()) };
        let s = s.as_table().ok_or("evani.toml: `[statement]` must be a table")?;
        for k in s.keys() {
            if !matches!(k.as_str(), "game_licence" | "third_party") {
                return Err(format!("evani.toml: unknown statement field `{k}` (game_licence, third_party)"));
            }
        }
        let game_licence = match s.get("game_licence") {
            None => None,
            Some(v) => Some(v.as_str().ok_or("evani.toml: `statement.game_licence` must be a string")?.to_string()),
        };
        let third_party = match s.get("third_party") {
            None => Vec::new(),
            Some(v) => v
                .as_array()
                .ok_or("evani.toml: `statement.third_party` must be a list of strings")?
                .iter()
                .map(|e| e.as_str().map(str::to_string).ok_or_else(|| "evani.toml: every `statement.third_party` entry must be a string".to_string()))
                .collect::<Result<_, _>>()?,
        };
        Ok(Self { game_licence, third_party })
    }
}

/// Everything the statement is made from.
pub struct Inputs<'a> {
    pub id: &'a str,
    pub manifest: &'a Manifest,
    pub statement: &'a Statement,
    pub engine_version: &'a str,
    pub engine_commit: &'a str,
    pub engine_dirty: bool,
    pub size: &'a BuildSize,
    /// The kit declares on-screen touch controls.
    pub touch: bool,
    /// A game kept outside the engine folder: its own commit and whether it
    /// has uncommitted changes (`None` for a game in `apps/`, whose commit
    /// is the engine's).
    pub game_commit: Option<(&'a str, bool)>,
}

/// The statement as pretty JSON (keys in alphabetical order, one trailing newline).
pub fn facts_json(i: &Inputs) -> String {
    let m = i.manifest;
    let mut modules: Vec<&str> = Vec::new();
    for (on, name) in [(m.net, "net"), (m.xr, "xr"), (m.models, "models"), (m.anim, "anim"), (m.ui, "ui"), (m.nature.is_some(), "nature"), (m.proc.is_some(), "proc")] {
        if on {
            modules.push(name);
        }
    }
    let mut input = vec!["keyboard", "mouse and touch (pointer)", "gamepad"];
    if i.touch {
        input.push("on-screen touch buttons");
    }
    if m.xr {
        input.push("xr controllers");
    }
    let (requests, personal) = if m.net {
        (
            "This game has the multiplayer (net) module: it talks to the game server named in its own settings, and to no other site.",
            "The engine collects none. In multiplayer, the game's state is sent to the game server the player joins.",
        )
    } else {
        (
            "None to other sites. The page fetches only the game's own files from the address it was opened at.",
            "None collected.",
        )
    };
    let mut v: Value = json!({
        "schema": "evani-build-facts/1",
        "about": "Generated by `cargo xtask build <id> --ship`. It sits beside the game files and is not loaded by the game, so it adds nothing to the download.",
        "game": {
            "id": i.id,
            "kit": m.kit,
            "look": m.look,
            "licence": i.statement.game_licence.as_deref().unwrap_or("see the LICENSE file in this package"),
        },
        "engine": {
            "name": "Evani.Dev",
            "version": i.engine_version,
            "commit": i.engine_commit,
            "uncommitted_engine_changes": i.engine_dirty,
            "licence": "MIT",
            "licence_file": "ENGINE-LICENSE.txt",
            "licence_url": "https://opensource.org/license/mit",
        },
        "modules": {
            "effects": m.effects,
            "physics": m.physics.as_deref().unwrap_or("none"),
            "optional": modules,
            "live_tuning": false,
        },
        "download": {
            "wasm_bytes": i.size.wasm_raw,
            "wasm_gzip_bytes": i.size.wasm_gz,
            "js_bytes": i.size.js_raw,
            "js_gzip_bytes": i.size.js_gz,
            "html_bytes": i.size.html_raw,
            "total_bytes": i.size.total_raw(),
            "total_gzip_bytes": i.size.total_gz(),
            "note": "Code only (wasm, js, html); sizes are raw unless named gzip. Other game files, if any, are listed in the package manifest.",
        },
        "network": requests,
        "personal_data": personal,
        "ads": "none",
        "analytics": "none",
        "tracking": "none",
        "cookies": "none",
        "storage": "localStorage only, for settings and progress. If the browser refuses it, the game carries on without saving.",
        "input": input,
        "ai_use": {
            "development": "Made with AI coding assistants under the owner's direction (code and, where used, assets).",
            "while_playing": "No generative AI runs while the game plays. Game AI (opponents, pathfinding, procedural levels) is ordinary programmed logic, not generative.",
        },
        "content": {
            "original": true,
            "note": "All content is original to this project, or the rights are held.",
            "third_party": i.statement.third_party,
        },
    });
    if let (Some((commit, dirty)), Some(game)) = (i.game_commit, v.get_mut("game").and_then(Value::as_object_mut)) {
        game.insert("commit".into(), json!(commit));
        game.insert("uncommitted_changes".into(), json!(dirty));
    }
    let mut s = serde_json::to_string_pretty(&v).unwrap_or_default();
    s.push('\n');
    s
}

fn git(root: &Path, args: &[&str]) -> Option<String> {
    std::process::Command::new("git")
        .args(args)
        .current_dir(root)
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
}

/// Writes [`FACTS_FILE`] and the engine notice into the ship folder `dist`.
pub fn write(app: &AppDir, size: &BuildSize, dist: &Path) -> Result<(), String> {
    let root = crate::workspace_root();
    let text = std::fs::read_to_string(app.dir.join("evani.toml")).map_err(|e| e.to_string())?;
    let statement = Statement::parse(&text)?;
    let commit = git(&root, &["rev-parse", "--short=7", "HEAD"]).unwrap_or_else(|| "unknown".into());
    let dirty = crate::review::engine_dirty(&root);
    let touch = kit_has_touch(&app.kit_dir());
    let game = app.external.as_ref().map(|e| crate::app_dir::game_commit(&e.root).unwrap_or_else(|| ("unknown".into(), false)));
    let manifest = app.manifest.clone().ship();
    let out = facts_json(&Inputs {
        id: &app.name,
        manifest: &manifest,
        statement: &statement,
        engine_version: env!("CARGO_PKG_VERSION"),
        engine_commit: &commit,
        engine_dirty: dirty,
        size,
        touch,
        game_commit: game.as_ref().map(|(c, d)| (c.as_str(), *d)),
    });
    evani_guide::playground::write_engine_notice(&root, dist)?;
    std::fs::write(dist.join(FACTS_FILE), out).map_err(|e| format!("{FACTS_FILE}: {e}"))?;
    println!("  statement: {FACTS_FILE} and {} written beside index.html (not part of the download)", evani_guide::playground::ENGINE_NOTICE_FILE);
    Ok(())
}

/// The kit crate (at `kit_dir`) calls `touch_controls(` somewhere in its source.
fn kit_has_touch(kit_dir: &Path) -> bool {
    fn scan(dir: &Path) -> bool {
        let Ok(rd) = std::fs::read_dir(dir) else { return false };
        rd.flatten().any(|e| {
            let p = e.path();
            if p.is_dir() {
                scan(&p)
            } else {
                p.extension().is_some_and(|x| x == "rs") && std::fs::read_to_string(&p).is_ok_and(|t| t.contains("touch_controls("))
            }
        })
    }
    scan(&kit_dir.join("src"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest(net: bool) -> Manifest {
        let net = if net { "true" } else { "false" };
        Manifest::parse(&format!("name = \"demo\"\nkit = \"k\"\nlook = \"l\"\neffects = [\"juice\"]\n[modules]\nphysics = \"none\"\nnet = {net}\nlive = true\n"))
            .expect("manifest")
    }

    fn facts(net: bool, st: &Statement) -> Value {
        facts_with(net, st, None)
    }

    fn facts_with(net: bool, st: &Statement, game_commit: Option<(&str, bool)>) -> Value {
        let size = BuildSize { wasm_raw: 600, wasm_gz: 300, js_raw: 40, js_gz: 20, html_raw: 10, ..Default::default() };
        let m = manifest(net).ship();
        let s = facts_json(&Inputs {
            id: "demo",
            manifest: &m,
            statement: st,
            engine_version: "0.1.0",
            engine_commit: "abc1234",
            engine_dirty: false,
            size: &size,
            touch: true,
            game_commit,
        });
        assert!(s.ends_with("}\n"));
        serde_json::from_str(&s).expect("valid json")
    }

    #[test]
    fn states_engine_sizes_and_no_tracking() {
        let v = facts(false, &Statement::default());
        assert_eq!(v["engine"]["commit"], "abc1234");
        assert_eq!(v["engine"]["licence"], "MIT");
        assert_eq!(v["engine"]["licence_file"], "ENGINE-LICENSE.txt");
        assert_eq!(v["download"]["total_bytes"], 650);
        assert_eq!(v["download"]["total_gzip_bytes"], 330);
        assert_eq!(v["modules"]["live_tuning"], false);
        assert_eq!(v["modules"]["effects"][0], "juice");
        for k in ["ads", "analytics", "tracking", "cookies"] {
            assert_eq!(v[k], "none", "{k}");
        }
        assert!(v["network"].as_str().unwrap_or("").starts_with("None to other sites"));
        assert_eq!(v["input"][3], "on-screen touch buttons");
        assert_eq!(v["game"]["licence"], "see the LICENSE file in this package");
    }

    #[test]
    fn an_outside_game_records_its_own_commit_beside_the_engine() {
        let inside = facts(false, &Statement::default());
        assert!(inside["game"].get("commit").is_none() && inside["game"].get("uncommitted_changes").is_none(), "a game in apps/ is unchanged");
        let v = facts_with(false, &Statement::default(), Some(("f00d123", true)));
        assert_eq!(v["game"]["commit"], "f00d123");
        assert_eq!(v["game"]["uncommitted_changes"], true);
        assert_eq!(v["engine"]["commit"], "abc1234");
        assert_eq!(v["game"]["id"], "demo");
    }

    #[test]
    fn net_module_changes_the_network_statement() {
        let v = facts(true, &Statement::default());
        assert!(v["network"].as_str().unwrap_or("").contains("multiplayer"));
        assert_eq!(v["modules"]["optional"][0], "net");
    }

    #[test]
    fn statement_table_is_read_and_checked() {
        let st = Statement::parse("name = \"x\"\n[statement]\ngame_licence = \"MIT\"\nthird_party = [\"Font X (OFL)\"]\n").expect("parse");
        let v = facts(false, &st);
        assert_eq!(v["game"]["licence"], "MIT");
        assert_eq!(v["content"]["third_party"][0], "Font X (OFL)");
        assert!(Statement::parse("[statement]\nads = true\n").is_err());
        assert_eq!(Statement::parse("name = \"x\"\n").expect("none"), Statement::default());
    }
}
